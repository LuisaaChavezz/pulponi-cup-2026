export const KRAKEN_MODE = {
  TIED: 'tied',
  DANGER: 'danger',
  SAFE: 'safe',
};

export function getKrakenMessagesForMode(mode) {
  switch (mode) {
    case KRAKEN_MODE.TIED:
      return KRAKEN_MESSAGES_TIED;
    case KRAKEN_MODE.DANGER:
      return KRAKEN_MESSAGES_DANGER;
    default:
      return KRAKEN_MESSAGES_SAFE;
  }
}

export function resolveKrakenMode(top1Points, top2Points) {
  const diff = Number(top1Points ?? 0) - Number(top2Points ?? 0);
  if (diff === 0) return KRAKEN_MODE.TIED;
  if (diff <= 2) return KRAKEN_MODE.DANGER;
  return KRAKEN_MODE.SAFE;
}
